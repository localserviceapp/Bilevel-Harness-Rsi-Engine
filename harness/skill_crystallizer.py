import ast
import math
from pathlib import Path
from typing import Any, Dict, Tuple
from macro_epoch2_router import MacroEpoch2Router

class SkillCrystallizer:
    """
    Section 2.1 Capacity-Bounded Library Crystallization (K_lib).
    Checks Gate-0 AST security and Halstead volume bounds [V_min, V_max],
    then writes verified stateless primitives into harness/stdlib_primitives.py.
    """

    def __init__(self, lib_path: str = "harness/stdlib_primitives.py", k_max: int = 32, v_min: float = 15.0, v_max: float = 2500.0):
        self.lib_path = Path(lib_path)
        self.k_max = k_max
        self.v_min = v_min
        self.v_max = v_max
        self.primitives: Dict[str, Dict[str, Any]] = {}
        self._init_library_file()

    def _init_library_file(self):
        if not self.lib_path.exists():
            self.lib_path.write_text('"""Crystallized Verified Skill Library (L_tools)."""\n\n')

    @staticmethod
    def compute_halstead_volume(code_str: str) -> float:
        tree = ast.parse(code_str)
        operators, operands = [], []
        for node in ast.walk(tree):
            if isinstance(node, (ast.Add, ast.Sub, ast.Mult, ast.Div, ast.Mod, ast.Eq, ast.NotEq,
                                 ast.Lt, ast.LtE, ast.Gt, ast.GtE, ast.And, ast.Or, ast.Assign,
                                 ast.AugAssign, ast.Return, ast.For, ast.If, ast.Call)):
                operators.append(type(node).__name__)
            elif isinstance(node, ast.Name):
                operands.append(node.id)
            elif isinstance(node, ast.Constant):
                operands.append(repr(node.value))
        N = len(operators) + len(operands)
        eta = len(set(operators)) + len(set(operands))
        return round(N * math.log2(eta), 2) if eta > 1 else 0.0

    def admit_primitive(self, name: str, code_str: str, utility_score: float = 1.0) -> Tuple[bool, str]:
        ok_g0, msg_g0 = MacroEpoch2Router.check_gate0_ast(code_str)
        if not ok_g0:
            return False, f"Gate-0 rejected primitive: {msg_g0}"

        vol = self.compute_halstead_volume(code_str)
        if not (self.v_min <= vol <= self.v_max):
            return False, f"Halstead volume {vol} outside [{self.v_min}, {self.v_max}]"

        if len(self.primitives) >= self.k_max and name not in self.primitives:
            lowest_key = min(self.primitives, key=lambda k: self.primitives[k]["utility"])
            del self.primitives[lowest_key]

        self.primitives[name] = {
            "code": code_str.strip(),
            "halstead_volume": vol,
            "utility": utility_score
        }
        self._flush_to_disk()
        return True, f"Admitted ({vol} Halstead bits)"

    def _flush_to_disk(self):
        lines = ['"""Crystallized Verified Skill Library (L_tools) - Auto-Generated by Loop 2."""\n']
        for meta in self.primitives.values():
            lines.append(meta["code"] + "\n")
        self.lib_path.write_text("\n".join(lines))
