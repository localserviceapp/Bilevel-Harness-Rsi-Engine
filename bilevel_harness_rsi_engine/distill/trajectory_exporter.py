import json
import math
from dataclasses import dataclass
from typing import Dict, List


@dataclass
class GRPOCandidateSample:
    candidate_id: str
    code: str
    vault_correct: int           # V(y_i, p) in {0, 1}
    shadow_invariant_ratio: float  # psi_sh(y_i, p) in [0, 1]
    normalized_tokens: float     # tau_bar(y_i) = tau(y_i) / tau_0
    old_logprob: float
    new_logprob: float
    ref_logprob: float


class RLVRDistillationEngine:
    """
    Loop 4 (Parametric Distillation, dt_4 ~ 10^6 s):
    Harvests 100% Shadow- and Vault-verified trajectories (generated by Gemini or open-weights Loop 1)
    and distills them into open-weights student parameters (e.g. Qwen2.5-Coder-7B-Instruct) via GRPO.
    """

    def __init__(
        self,
        eta_sh: float = 0.20,
        eta_tau: float = 0.05,
        max_tau_bar: float = 4.0,
        clip_eps: float = 0.20,
        beta_kl: float = 0.04,
        delta_eps: float = 1e-8,
    ):
        if not (eta_sh > 0 and eta_tau > 0):
            raise ValueError("Hyperparameters eta_sh and eta_tau must be strictly positive.")
        if eta_sh >= 1.0 - eta_tau * max_tau_bar:
            raise ValueError(
                f"Boundary violation: eta_sh ({eta_sh}) must satisfy eta_sh < 1 - eta_tau * max_tau_bar "
                f"({1.0 - eta_tau * max_tau_bar:.4f}) so V=0 never out-scores V=1."
            )
        self.eta_sh = eta_sh
        self.eta_tau = eta_tau
        self.max_tau_bar = max_tau_bar
        self.clip_eps = clip_eps
        self.beta_kl = beta_kl
        self.delta_eps = delta_eps

    def compute_verifiable_reward(
        self, v_pass: int, psi_sh: float, tau_bar: float
    ) -> float:
        capped_tau = min(max(0.0, tau_bar), self.max_tau_bar)
        return round(float(v_pass) + self.eta_sh * psi_sh - self.eta_tau * capped_tau, 6)

    def compute_grpo_group_metrics(
        self, samples: List[GRPOCandidateSample]
    ) -> Dict[str, object]:
        if not samples:
            raise ValueError("Sample group cannot be empty.")

        rewards = [
            self.compute_verifiable_reward(s.vault_correct, s.shadow_invariant_ratio, s.normalized_tokens)
            for s in samples
        ]
        g_size = len(rewards)
        mu_r = sum(rewards) / g_size
        var_r = sum((r - mu_r) ** 2 for r in rewards) / g_size
        sigma_r = math.sqrt(var_r)

        advantages = [(r - mu_r) / (sigma_r + self.delta_eps) for r in rewards]

        surrogate_terms = []
        kl_terms = []
        for s, adv in zip(samples, advantages):
            ratio = math.exp(s.new_logprob - s.old_logprob)
            clipped_ratio = min(max(ratio, 1.0 - self.clip_eps), 1.0 + self.clip_eps)
            surr = min(ratio * adv, clipped_ratio * adv)

            log_diff = s.ref_logprob - s.new_logprob
            kl_i = math.exp(log_diff) - log_diff - 1.0

            surrogate_terms.append(surr - self.beta_kl * kl_i)
            kl_terms.append(kl_i)

        return {
            "rewards": [round(r, 6) for r in rewards],
            "advantages": [round(a, 6) for a in advantages],
            "mean_kl": round(sum(kl_terms) / g_size, 6),
            "grpo_objective": round(sum(surrogate_terms) / g_size, 6),
        }

    @staticmethod
    def binary_entropy_bits(eps_0: float) -> float:
        if eps_0 <= 0.0 or eps_0 >= 1.0:
            return 0.0
        return -eps_0 * math.log2(eps_0) - (1.0 - eps_0) * math.log2(1.0 - eps_0)

    @classmethod
    def compute_fano_compression_bound(
        cls,
        h_s_dag_given_p: float,
        i_s_dag_c_star_given_p: float,
        eps_0: float,
        support_size_c_star: int,
    ) -> float:
        h_b = cls.binary_entropy_bits(eps_0)
        fano_penalty = h_b + eps_0 * math.log2(max(1, support_size_c_star))
        denom = i_s_dag_c_star_given_p - fano_penalty
        if denom <= 0.0:
            raise ValueError("Mutual information I(S_DAG; C^* | P) must exceed Fano penalty.")
        return round(h_s_dag_given_p / denom, 6)

    @staticmethod
    def export_verified_trajectories_jsonl(trajectories: List[Dict], output_path: str) -> int:
        count = 0
        with open(output_path, "w", encoding="utf-8") as f:
            for item in trajectories:
                if item.get("vault_pass_rate") == 1.0 and item.get("invariants_passed_ratio") == 1.0:
                    f.write(json.dumps(item) + "\n")
                    count += 1
        return count
